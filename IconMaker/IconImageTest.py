# カラー定義（ANSIエスケープコード用）
_ = "\033[48;5;232m  \033[0m"  # 黒背景
R = "\033[48;5;196m  \033[0m"  # 赤リボン
B = "\033[48;5;21m  \033[0m"   # 青リボン
G = "\033[48;5;220m  \033[0m"  # 金メダル
W = "\033[48;5;255m  \033[0m"  # 白（輝き）

# 8x8 マトリクスデータ
medal_8x8 = [
    [R, B, _, _, _, _, _, _],
    [_, R, B, _, _, _, _, _],
    [_, _, R, B, _, _, _, _],
    [_, _, _, G, G, G, _, _],
    [_, _, G, G, W, G, G, _],
    [_, _, G, G, G, G, G, _],
    [_, _, G, G, G, G, G, _],
    [_, _, _, G, G, G, _, _]
]

# コンソールに描画
for row in medal_8x8:
    print("".join(row))
